// No node imports here: this file also runs in a browser. It needs the pull request's changes against its base
// (`changes`); on a push scan it passes. It judges changed paths, never the PR title: a change to product code
// (added, modified or renamed) with no test file changed in the same pull request is reported. Test-only,
// docs-only and generated changes pass. gel.json can tune it:
//   "tests_with_change": { "source": [globs that count as product code], "tests": [globs that count as tests],
//                          "exempt": [globs never asked for a test] }
import { matchAny } from "../../lib/glob.mjs";

export const name = "tests-with-change";

const CODE_EXT = "{js,mjs,cjs,jsx,ts,tsx,py,go,rs,rb,java,kt,swift,php,cs,c,cc,cpp,h,hpp,sh,star}";
const CODE_RE = new RegExp(`\\.(${CODE_EXT.slice(1, -1).split(",").join("|")})$`, "i");
export const TESTS = [
  "tests/**", "test/**", "spec/**", "**/__tests__/**", "**/*.test.*", "**/*.spec.*", "**/test_*.py", "**/*_test.py",
  "**/*_test.go", "**/*_spec.rb", "**/*Test.java", "**/*Tests.cs", "**/src/test/**", "e2e/**", "**/e2e/**",
];
export const EXEMPT = [
  "dist/**", "**/dist/**", "build/**", ".flisk/**", ".flisk-out/**", "**/*.autogenerated.*", "**/generated/**", "**/*.generated.*",
  "**/*.min.js", "**/*.d.ts", "**/*.config.*", "**/vendor/**", "**/node_modules/**", "**/fixtures/**", "**/examples/**", "docs/**",
  "bench/**", "site/**", "scripts/**",
];

// product code: source by extension (or `source` globs), not a test, not generated or exempt. verify and perf-budget share it.
export function isSourceFile(f, c = {}) {
  const exempt = [...EXEMPT, ...(c?.exempt ?? [])];
  return (c?.source ? matchAny(c.source, f) : CODE_RE.test(f)) && !matchAny(c?.tests ?? TESTS, f) && !matchAny(exempt, f);
}

export function run({ changes, cfg }) {
  if (!changes) return { pass: true, findings: [] };
  const c = cfg?.tests_with_change ?? {};
  const tests = c.tests ?? TESTS;
  const exempt = [...EXEMPT, ...(c.exempt ?? [])];
  const isSource = (f) => (c.source ? matchAny(c.source, f) : CODE_RE.test(f)) && !matchAny(tests, f) && !matchAny(exempt, f);
  const touched = changes.filter((x) => x.status !== "D");
  if (touched.some((x) => matchAny(tests, x.file))) return { pass: true, findings: [] };
  // A deleted test is a test change too: removing code and its tests together is fine.
  if (changes.some((x) => x.status === "D" && matchAny(tests, x.from ?? x.file))) return { pass: true, findings: [] };
  const src = touched.filter((x) => isSource(x.file));
  if (!src.length) return { pass: true, findings: [] };
  return {
    pass: false,
    findings: [{ file: src[0].file, line: 1, message: `${src.length} product file${src.length > 1 ? "s" : ""} changed (${src.slice(0, 3).map((x) => x.file).join(", ")}${src.length > 3 ? ", ..." : ""}) and no test file changed in this pull request` }],
  };
}
